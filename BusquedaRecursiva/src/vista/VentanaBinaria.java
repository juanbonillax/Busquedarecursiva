    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
  int[] vector = new BusquedaRecursiva(10).retornarVector();

Arrays.sort(vector);

String textoVector = "";

for(int i = 0; i < vector.length; i++){
    textoVector += "[" + i + "] " + vector[i] + "\n";
}

txtVector.setText(textoVector);

int valor = Integer.parseInt(txtValor.getText());
BusquedaRecursiva busqueda = new BusquedaRecursiva(10);

int posicion = busqueda.buscarBinaria(
    vector, 0, vector.length - 1, valor
);

if (posicion != -1) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "El valor " + valor + " fue encontrado en la posición " + posicion);
} else {
    javax.swing.JOptionPane.showMessageDialog(this,
        "El valor " + valor + " no fue encontrado.");
}
    }//GEN-LAST:event_btnBuscarActionPerformed

